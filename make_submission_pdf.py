"""Turn a model's answers (exam_taker.py output) into a submission PDF for the scoring toolkit.

Usage (from the toolkit root, with the venv active):
    python make_submission_pdf.py EXAM_JSON OUTPUT_JSON OUT_PDF [--model NAME]

Example:
    python make_submission_pdf.py \
        ../aiscientist-dhest/data/signals-and-systems/exam_hs19.json \
        ../aiscientist-dhest/llm_output/signals-and-systems/output_hs19.json \
        workspaces/ss_hs19/RawExams/Exam001.pdf --model gemma-4-31B-it
"""
import argparse, json, os, re, sys
from xml.sax.saxutils import escape

from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import cm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer

FONT_CANDIDATES = ["/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
                   "/usr/share/fonts/dejavu/DejaVuSans.ttf",
                   "/Library/Fonts/Arial Unicode.ttf"]


def pick_font():
    for path in FONT_CANDIDATES:
        if os.path.exists(path):
            pdfmetrics.registerFont(TTFont("Uni", path))
            return "Uni"
    print("Warning: no Unicode font found; non-Latin symbols may not render.", file=sys.stderr)
    return "Helvetica"


def label_of(question):
    m = re.search(r"Question ([^:]+):", question["text"])
    return m.group(1).strip() if m else question["id"]


def fmt(answer):
    if answer is None:
        return "(no answer given)"
    if isinstance(answer, list):
        return "; ".join(str(a) for a in answer)
    return str(answer)


def para(text, style):
    return Paragraph(escape(text).replace("\n", "<br/>"), style)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("exam_json")
    ap.add_argument("output_json")
    ap.add_argument("out_pdf")
    ap.add_argument("--model", default="unknown model")
    a = ap.parse_args()

    exam = json.load(open(a.exam_json, encoding="utf-8"))
    answers = {x["id"]: x.get("answer") for x in json.load(open(a.output_json, encoding="utf-8")).get("answers", [])}

    if os.path.exists(a.out_pdf):
        sys.exit(f"Refusing to overwrite existing {a.out_pdf}")
    os.makedirs(os.path.dirname(a.out_pdf) or ".", exist_ok=True)

    font = pick_font()
    ss = getSampleStyleSheet()
    h = ParagraphStyle("h", parent=ss["Heading2"], fontName=font)
    q = ParagraphStyle("q", parent=ss["BodyText"], fontName=font, fontSize=9, textColor="#555555")
    ans = ParagraphStyle("a", parent=ss["BodyText"], fontName=font, fontSize=11, leading=15)
    title = ParagraphStyle("t", parent=ss["Title"], fontName=font)

    story = [para(exam.get("title", exam.get("examId", "")), title),
             para(f"Submission: answers generated by {a.model}", q), Spacer(1, 0.5 * cm)]
    missing = 0
    for question in exam["questions"]:
        if question["id"] not in answers:
            missing += 1
        story += [para(f"Question {label_of(question)}", h),
                  para(question["text"].split(f"Question {label_of(question)}:")[-1].strip(), q),
                  Spacer(1, 0.15 * cm),
                  para("Answer: " + fmt(answers.get(question["id"])), ans),
                  Spacer(1, 0.4 * cm)]

    SimpleDocTemplate(a.out_pdf, pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm,
                      topMargin=2 * cm, bottomMargin=2 * cm).build(story)
    print(f"Wrote {a.out_pdf}: {len(exam['questions'])} questions, {missing} without an answer.")


if __name__ == "__main__":
    main()
